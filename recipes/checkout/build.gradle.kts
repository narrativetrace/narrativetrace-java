// `recipes/checkout` IS documentation/recipes/ — the one checkout every recipe page runs. Each
// page embeds this project's sources and the output of a real run of them (snippetCheck/
// snippetSync, root build.gradle.kts, beside translationCheck), the same arrangement
// `sixty-seconds` has with documentation/sixty-seconds.md: rule 8, docs as tests.
//
// Like that module, this one depends on the in-tree modules by source (`project(...)`) rather than
// on the published coordinates the pages tell a reader to install, so a change in the runtime is
// caught the moment this module rebuilds instead of against a possibly-stale jar. Proving the
// pages' published-coordinate blocks resolve is the cold walk's job, not this module's.
dependencies {
    implementation(project(":narrativetrace-core"))
    implementation(project(":narrativetrace-proxy"))

    testImplementation(project(":narrativetrace-junit5"))
    testImplementation("org.junit.jupiter:junit-jupiter:5.11.4")
    testImplementation("org.junit.platform:junit-platform-launcher:1.11.4")
    testImplementation("org.assertj:assertj-core:3.27.7")

    // Every page's log lines come from the project's own logger, not from a NarrativeTrace writer:
    // narrativetrace-slf4j attaches itself to the pipeline once it is on the classpath
    // (documentation/configuration-guide.md §7), and logback-test.xml decides where its events go.
    testRuntimeOnly(project(":narrativetrace-slf4j"))
    testRuntimeOnly("ch.qos.logback:logback-classic:1.5.38")
}

// Where every file a recipe page embeds is written. One directory per page, so no two runs can
// claim the same artifact, and the whole tree is regenerated by `./gradlew :recipes-checkout:test`.
val recipeOutput = layout.buildDirectory.dir("narrativetrace/recipes")

// A fixture is a @Test that exists to be run BY another test (the JUnit Platform launcher, in
// process), because what it does is fail, or be approved, or be compared against its own earlier
// shape. Running it directly would fail this module's build for doing exactly what it is for.
tasks.test {
    exclude("**/*Fixture.class")
    systemProperty("narrativetrace.recipes.log", recipeOutput.get().asFile.resolve("suite.log").path)
    // The suite's own trace artifacts, next to the per-page ones the pages embed.
    systemProperty("narrativetrace.outputDir", layout.buildDirectory.dir("narrativetrace").get().asFile.path)
    outputs.dir(recipeOutput)
}

// The two pages whose output IS log output need the log of one scenario alone in one file, and the
// appender's file name is a property of the JVM, not of a test — so each gets its own test JVM.
// `test` above runs the same classes with the suite-wide log file; these two tasks are what the
// pages' embedded log blocks come from.
fun registerLogCapture(taskName: String, testClass: String, slug: String) =
    tasks.register<Test>(taskName) {
        group = "documentation"
        description = "Captures documentation/recipes/$slug.md's log output from a real run"
        testClassesDirs = sourceSets["test"].output.classesDirs
        classpath = sourceSets["test"].runtimeClasspath
        useJUnitPlatform()
        filter { includeTestsMatching("com.example.checkout.$testClass") }
        systemProperty(
            "narrativetrace.recipes.log",
            recipeOutput.get().asFile.resolve("$slug/checkout.log").path
        )
        systemProperty("narrativetrace.outputDir", layout.buildDirectory.dir("narrativetrace").get().asFile.path)
        outputs.dir(recipeOutput.get().asFile.resolve(slug))
    }

val recipeAddLoggingLog =
    registerLogCapture("recipeAddLoggingLog", "AddLoggingRecipeTest", "add-logging-to-this-service")

// The review page's log block is the DETAIL run of one scenario, so this task runs the fixture
// itself (`tasks.test` skips every *Fixture; a task that names one runs it) rather than the driver,
// whose two nested runs at two capture levels would interleave in one file.
val recipeReviewFlowLog =
    registerLogCapture(
        "recipeReviewFlowLog",
        "CheckoutReviewFixture",
        "review-a-complex-flow-before-changing-it"
    )

// Every page's evidence is produced by `check`, never by a developer remembering to ask for it.
tasks.named("check") {
    dependsOn(recipeAddLoggingLog, recipeReviewFlowLog)
}
